# 1. Create a dictionary
fruit_colors = {
    "apple": "red",
    "banana": "yellow",
    "grape": "green"
}

# 2. Print the whole dictionary
print("All fruits and colors:", fruit_colors)

# 3. Look up one specific fruit color
print("The color of a banana is:", fruit_colors["banana"])

# 4. Add a new fruit to the dictionary
fruit_colors["orange"] = "orange"
print("Updated dictionary:", fruit_colors)
